"""Compose apps/web/public/og-card.png, the Open Graph card.

Run from the repo root, after a UI change that dates the card:

    python3 -m pip install --user Pillow
    python3 scripts/make-og-card.py

This is not wired into the build or CI. The card changes about as often as the
hero shot does, so it is committed as a PNG and regenerated by hand; carrying a
Python step through a Node build to redraw one image a couple of times a year
is not a trade worth making.

Three constraints the card has to keep, because they are what actually breaks:
LinkedIn's documented ceiling is 5 MB and its large-card floor is 1200x630, so
the delivered file wants to sit well inside the first and well past the second;
the 1.91:1 ratio is what every scraper crops to; and og:image:width/height in
the page must agree with the bytes, or the tags are a claim the file does not
honour. The card this replaced was the raw 3680x2268 hero shot at 1.3 MB.

The fourth constraint shaped the drawing. LinkedIn does not always grant a link
the full-width layout -- in the mobile composer it renders the card as a
~128pt-wide thumbnail beside the title, one tenth of nominal width, where a
28px tagline arrives as 3pt of grey fuzz. So the card is composed as a poster,
not a slide: one enormous wordmark that is still a word at 128pt, and behind it
a deliberately cropped piece of the resolution graph -- nodes and edges running
off three sides, the policy categories stacked down the right and clipped top
and bottom. The crop is the point. A whole diagram shrunk to fit reads as
nothing; a fragment of a big one reads as a tool with more behind it.

Small copy exists only for the full-size view, where it costs nothing. Nothing
here is load-bearing at thumbnail size except the wordmark and the silhouette.
"""
import sys
from math import hypot
from PIL import Image, ImageDraw, ImageFont

OUT = sys.argv[1] if len(sys.argv) > 1 else "apps/web/public/og-card.png"

# 1200x630 is the floor LinkedIn documents for its large-card layout, and
# sitting exactly on a floor is a bad place to be: it also renders the card on
# high-DPI screens, where 1200 wide is a 2x image at 600 CSS px. S=2 emits
# 2400x1260 -- comfortably past any threshold and sharp on a retina display.
S = float(sys.argv[2]) if len(sys.argv) > 2 else 2.0

# Everything is drawn at SS times the delivered scale and resampled down at the
# end. PIL antialiases nothing it draws: a 3px bezier, a rounded corner and the
# aircraft polygon all come out stair-stepped if they are rendered straight to
# final size. On a card whose whole job is to look considered, that is the
# first thing anyone notices.
SS = 2
R = S * SS
def s_(v):
    return round(v * R)

W, H = s_(1200), s_(630)
OUT_W, OUT_H = round(1200 * S), round(630 * S)
BG   = (9, 12, 20)
PANE = (19, 26, 42)
SKY  = (56, 189, 248)
TX   = (237, 242, 249)
MUT  = (148, 163, 184)
DIM  = (100, 116, 139)
EDGE = (44, 57, 80)
WIRE = (62, 80, 110)

ORANGE, INDIGO, ROSE = (251, 146, 60), (129, 140, 248), (251, 113, 133)
VIOLET, EMERALD = (167, 139, 250), (52, 211, 153)


def font(size, bold=False):
    try:
        f = ImageFont.truetype("/System/Library/Fonts/SFNS.ttf", size)
        f.set_variation_by_name("Bold" if bold else "Regular")
        return f
    except Exception:
        p = "Arial Bold.ttf" if bold else "Arial.ttf"
        return ImageFont.truetype("/System/Library/Fonts/Supplemental/" + p, size)


def tracked(xy, text, f, fill, track):
    """Set a caps run a glyph at a time, with air between the letters.

    PIL has no letter-spacing. Small all-caps set solid reads as a smudge, and
    these are the two runs that carry the categories. Drawing per glyph throws
    away kerning pairs, which is why it is used only on caps -- there are none
    worth keeping in DEVICE CONFIGURATION.
    """
    x, y = xy
    for ch in text:
        d.text((x, y), ch, font=f, fill=fill)
        x += d.textlength(ch, font=f) + track


card = Image.new("RGB", (W, H), BG)

# A slow glow under the graph, so the right half has depth rather than reading
# as flat panels on flat black. Built small and scaled up; a per-pixel loop at
# 2400x1260 costs seconds for a gradient nobody can resolve.
glow = Image.new("L", (240, 126), 0)
gp = glow.load()
for gy in range(126):
    for gx in range(240):
        dist = hypot((gx - 138) / 120.0, (gy - 60) / 78.0)
        gp[gx, gy] = max(0, int(90 * (1 - min(1.0, dist)) ** 1.5))
card = Image.composite(Image.new("RGB", (W, H), (26, 48, 74)), card,
                       glow.resize((W, H), Image.BICUBIC))

d = ImageDraw.Draw(card, "RGBA")


def bezier(p0, p3, k=0.58, n=48):
    """Cubic with horizontal handles -- the shape the app's own graph draws."""
    dx = (p3[0] - p0[0]) * k
    p1, p2 = (p0[0] + dx, p0[1]), (p3[0] - dx, p3[1])
    pts = []
    for i in range(n + 1):
        t = i / n
        u = 1 - t
        pts.append((
            u**3 * p0[0] + 3 * u*u*t * p1[0] + 3 * u*t*t * p2[0] + t**3 * p3[0],
            u**3 * p0[1] + 3 * u*u*t * p1[1] + 3 * u*t*t * p2[1] + t**3 * p3[1],
        ))
    return pts


def node(box, label, sub=None, accent=None):
    d.rounded_rectangle(box, radius=s_(14), fill=PANE,
                        outline=accent or EDGE, width=max(2, s_(2)))
    x, y0, _, y1 = box
    if sub:
        d.text((x + s_(20), (y0 + y1) / 2 - s_(26)), label, font=font(s_(22), True), fill=TX)
        d.text((x + s_(20), (y0 + y1) / 2 + s_(4)), sub, font=font(s_(17)), fill=DIM)
    else:
        d.text((x + s_(20), (y0 + y1) / 2 - s_(14)), label, font=font(s_(22), True), fill=TX)


# ------------------------------------------------- right: the category stack
# Clipped top and bottom on purpose. The list is longer than the card.
CATS = [
    ("DEVICE CONFIGURATION", ORANGE,
     ["Wi-Fi — Corporate", "VPN — Always On", "Delivery Optimization"]),
    ("SETTINGS CATALOG", INDIGO,
     ["Defender — ASR Rules", "Edge — Security Baseline", "LAPS", "Power & Sleep"]),
    ("ENDPOINT SECURITY", SKY,
     ["BitLocker — Silent Enable", "Firewall Profile", "Account Protection"]),
    ("COMPLIANCE", EMERALD,
     ["Windows — Minimum OS", "Defender Healthy"]),
    ("ADMIN TEMPLATES", VIOLET,
     ["OneDrive — Known Folder Move", "Chrome — Managed"]),
]

RX, RW = s_(876), s_(404)          # right edge lands at 1280: 80px off-canvas
y = s_(-74)
cat_anchors = []
for title, accent, items in CATS:
    h = s_(36) + len(items) * s_(31) + s_(18)
    d.rounded_rectangle([RX, y, RX + RW, y + h], radius=s_(14),
                        fill=(16, 22, 36), outline=EDGE, width=max(2, s_(2)))
    d.rounded_rectangle([RX, y, RX + s_(6), y + h], radius=s_(3), fill=accent)
    tracked((RX + s_(22), y + s_(11)), title, font(s_(16), True), accent, s_(0.9))
    for i, it in enumerate(items):
        iy = y + s_(44) + i * s_(31)
        d.ellipse([RX + s_(24), iy + s_(7), RX + s_(32), iy + s_(15)], fill=accent + (170,))
        d.text((RX + s_(44), iy), it, font=font(s_(17)), fill=(176, 189, 207))
    cat_anchors.append((RX, y + h / 2))
    y += h + s_(14)

# -------------------------------------------------- left/centre: the resolve
# One endpoint, three group nodes, edges fanning into the category stack. The
# endpoint is cropped by the left edge so the viewer lands mid-graph.
ep = [s_(-40), s_(58), s_(330), s_(140)]
grp = [
    ([s_(470), s_(44), s_(760), s_(126)], "All Devices", "dynamic · 1,284"),
    ([s_(470), s_(188), s_(760), s_(270)], "Autopilot — Windows", "assigned"),
    ([s_(470), s_(332), s_(760), s_(414)], "All Users", "dynamic · 903"),
]

for box, *_ in grp:
    d.line(bezier((ep[2], (ep[1] + ep[3]) / 2), (box[0], (box[1] + box[3]) / 2)),
           fill=WIRE, width=max(2, s_(3)), joint="curve")

for gi, (box, *_) in enumerate(grp):
    src = (box[2], (box[1] + box[3]) / 2)
    for ci, anchor in enumerate(cat_anchors):
        if (gi + ci) % 3 == 2:          # a readable subset, not every pairing
            continue
        accent = CATS[ci][1]
        d.line(bezier(src, anchor), fill=accent + (60,), width=max(2, s_(3)), joint="curve")

node(ep, "WIN11-CORP-0427", "Entra joined · Autopilot", SKY)
node(grp[0][0], grp[0][1], grp[0][2])
node(grp[1][0], grp[1][1], grp[1][2], SKY)
node(grp[2][0], grp[2][1], grp[2][2])

# ------------------------------------------------------- bottom-left: scrim
# The graph runs under the wordmark rather than stopping politely beside it, so
# the corner is darkened back down until the type has its contrast returned.
scrim = Image.new("L", (288, 150), 0)
sp = scrim.load()
for sy in range(150):
    for sx in range(288):
        dist = hypot(sx / 222.0, (149 - sy) / 120.0)
        sp[sx, sy] = int(252 * (1 - min(1.0, dist)) ** 0.85)
card.paste(Image.new("RGB", (W, H), BG), (0, 0), scrim.resize((W, H), Image.BICUBIC))

d = ImageDraw.Draw(card, "RGBA")

PLANE = [
    (16, 4.5), (17.9, 8.1), (17.9, 11.4), (24.5, 15.4), (24.5, 17.8),
    (17.9, 15.8), (17.9, 20.1), (20.4, 22.0), (20.4, 23.9), (16, 22.7),
    (11.6, 23.9), (11.6, 22.0), (14.1, 20.1), (14.1, 15.8), (7.5, 17.8),
    (7.5, 15.4), (14.1, 11.4), (14.1, 8.1),
]
x0 = s_(76)
# s_() and not S: the glyph is in the same coordinate space as everything else,
# and scaling it by the delivered scale rather than the render scale silently
# halves it the moment supersampling is switched on.
g = s_(1.5)
d.polygon([(x0 + x * g, s_(236) + y_ * g) for x, y_ in PLANE], fill=SKY)
tracked((x0 + s_(50), s_(243)), "OPEN SOURCE  ·  READ-ONLY", font(s_(17), True), SKY, s_(1.1))

wm = font(s_(116), True)
d.text((x0 - s_(6), s_(282)), "Intune", font=wm, fill=TX)
d.text((x0 - s_(6), s_(398)), "Preflight", font=wm, fill=TX)

d.text((x0, s_(534)), "See what Intune applies to a device — before you deploy it.",
       font=font(s_(23)), fill=MUT)
d.text((x0, s_(572)), "kevinmalinoski.github.io/intune-preflight",
       font=font(s_(18), True), fill=DIM)

card = card.resize((OUT_W, OUT_H), Image.LANCZOS)
card.save(OUT, "PNG", optimize=True)
print("wrote %s  %dx%d" % (OUT, card.width, card.height))
