"""Compose apps/web/public/og-card.png, the 1200x630 Open Graph card.

Run from the repo root, after a UI change that dates the hero screenshot:

    python3 -m pip install --user Pillow
    python3 scripts/make-og-card.py

This is not wired into the build or CI. The card changes about as often as the
hero shot does, so it is committed as a PNG and regenerated by hand; carrying a
Python step through a Node build to redraw one image a couple of times a year
is not a trade worth making.

Two constraints the card has to keep, because they are what actually breaks:
LinkedIn drops images much over 1 MB, and the 1.91:1 ratio is what every
scraper crops to. The previous card was the raw 3680x2268 hero shot at 1.3 MB,
which is why it did not render.
"""
import sys
from PIL import Image, ImageDraw, ImageFont

SRC = "docs/img/01-simulator-overview.png"
OUT = sys.argv[1] if len(sys.argv) > 1 else "apps/web/public/og-card.png"

W, H = 1200, 630
BG = (11, 15, 23)
SKY = (56, 189, 248)
TX = (226, 232, 240)
MUT = (148, 163, 184)
DIM = (100, 116, 139)


def font(size, bold=False):
    try:
        f = ImageFont.truetype("/System/Library/Fonts/SFNS.ttf", size)
        f.set_variation_by_name("Bold" if bold else "Regular")
        return f
    except Exception:
        p = "Arial Bold.ttf" if bold else "Arial.ttf"
        return ImageFont.truetype("/System/Library/Fonts/Supplemental/" + p, size)


card = Image.new("RGB", (W, H), BG)

# ---- right side: the diagram region of the hero shot, faded in from the bg ----
shot = Image.open(SRC).convert("RGB")
# Region holding endpoint -> Autopilot -> groups -> policy bubbles.
crop = shot.crop((1450, 900, 2780, 2080))
pw = 780
panel = crop.resize((pw, int(pw * crop.height / crop.width)), Image.LANCZOS)

mask = Image.new("L", panel.size, 255)
md = ImageDraw.Draw(mask)
# Horizontal fade in from the left edge of the panel.
for x in range(260):
    md.line([(x, 0), (x, panel.height)], fill=int(255 * (x / 260) ** 1.6))
# Soften top and bottom so it sits in the background rather than on it.
for y in range(40):
    a = int(255 * (y / 40))
    for yy in (y, panel.height - 1 - y):
        row = mask.crop((0, yy, panel.width, yy + 1)).point(lambda v, a=a: v * a // 255)
        mask.paste(row, (0, yy))

card.paste(panel, (560, (H - panel.height) // 2), mask)

d = ImageDraw.Draw(card, "RGBA")
# Keep the left third dark enough for text to hold contrast over the panel.
for x in range(700):
    d.line([(x, 0), (x, H)], fill=BG + (int(255 * min(1.0, (700 - x) / 130)),))

# ---- brand mark: the favicon's aircraft, as a polygon ----
PLANE = [
    (16, 4.5), (17.9, 8.1), (17.9, 11.4), (24.5, 15.4), (24.5, 17.8),
    (17.9, 15.8), (17.9, 20.1), (20.4, 22.0), (20.4, 23.9), (16, 22.7),
    (11.6, 23.9), (11.6, 22.0), (14.1, 20.1), (14.1, 15.8), (7.5, 17.8),
    (7.5, 15.4), (14.1, 11.4), (14.1, 8.1),
]
s, ox, oy = 1.85, 72, 60
d.polygon([(ox + x * s, oy + y * s) for x, y in PLANE], fill=SKY)

x0 = 72
d.text((x0 + 62, 74), "OPEN SOURCE  ·  READ-ONLY", font=font(17, True), fill=SKY)
d.text((x0, 150), "Intune Preflight", font=font(68, True), fill=TX)
d.rounded_rectangle([x0, 243, x0 + 92, 249], radius=3, fill=SKY)

f28 = font(28)
d.text((x0, 288), "See what Intune applies to a device", font=f28, fill=MUT)
d.text((x0, 326), "— before you deploy it.", font=f28, fill=MUT)

f20 = font(20)
d.text((x0, 404), "Merged CSP baseline  ·  Conflicts  ·  Autopilot", font=f20, fill=DIM)
d.text((x0, 434), "Assignment filters  ·  Four platforms", font=f20, fill=DIM)

d.text((x0, 524), "No install.  No client secret.  Nothing leaves the tab.",
       font=font(19, True), fill=(203, 213, 225))
d.text((x0, 556), "kevinmalinoski.github.io/intune-preflight", font=font(18), fill=DIM)

card.save(OUT, "PNG", optimize=True)
print("wrote %s  %dx%d" % (OUT, card.width, card.height))
